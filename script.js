let lang = localStorage.getItem("site-lang") || "cs";
if (!copy[lang]) lang = "cs";

function renderLanguage() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (copy[lang][key]) el.textContent = copy[lang][key];
  });

  document.title = copy[lang].page_title;
  descriptionMeta?.setAttribute("content", copy[lang].page_description);
  ogTitleMeta?.setAttribute("content", copy[lang].page_title);
  ogDescriptionMeta?.setAttribute("content", copy[lang].page_description);
  twitterTitleMeta?.setAttribute("content", copy[lang].page_title);
  twitterDescriptionMeta?.setAttribute("content", copy[lang].page_description);

  langButton.textContent = lang === "cs" ? "EN" : "CZ";
  langButton.setAttribute(
    "aria-label",
    lang === "cs" ? "Switch language to English" : "Prepnout jazyk na cestinu"
  );
  updateThemeButton();
  puzzle.refreshStatus();
}

langButton.addEventListener("click", () => {
  lang = lang === "cs" ? "en" : "cs";
  localStorage.setItem("site-lang", lang);
  renderLanguage();
});

/* ============================================================
   theme (light / dark)
   ============================================================ */
let theme =
  localStorage.getItem("site-theme") ||
  (window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches
    ? "dark"
    : "light");

function updateThemeButton() {
  themeButton.textContent = theme === "dark" ? "☀" : "☾";
  themeButton.setAttribute(
    "aria-label",
    theme === "dark" ? copy[lang].theme_label_light : copy[lang].theme_label_dark
  );
}

function renderTheme() {
  document.documentElement.setAttribute("data-theme", theme);
  document
    .querySelector('meta[name="theme-color"]')
    ?.setAttribute("content", theme === "dark" ? "#14110a" : "#f7f1e6");
  updateThemeButton();
}

themeButton.addEventListener("click", () => {
  theme = theme === "dark" ? "light" : "dark";
  localStorage.setItem("site-theme", theme);
  renderTheme();
});

/* ============================================================
   reveal on scroll
   ============================================================ */
function initReveal() {
  const elements = document.querySelectorAll(".reveal");
  if (!("IntersectionObserver" in window)) {
    elements.forEach((el) => el.classList.add("is-visible"));
    return;
  }
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.15 }
  );
  elements.forEach((el) => observer.observe(el));
}

/* ============================================================
   chess puzzle — Paul Morphy, mate in two
   White: Kc8, Ra1, Pb6 · Black: Ka8, Bb8, Pa7, Pb7
   Solution: 1.Ra6! (…bxa6 2.b7# / …B-any 2.Rxa7#)
   ============================================================ */
const PIECE_GLYPHS = {
  wk: "♔", wq: "♕", wr: "♖", wb: "♗", wn: "♘", wp: "♙",
  bk: "♚", bq: "♛", br: "♜", bb: "♝", bn: "♞", bp: "♟",
};

const START_POSITION = {
  a8: "bk", b8: "bb", c8: "wk",
  a7: "bp", b7: "bp",
  b6: "wp",
  a1: "wr",
};

const FILES = ["a", "b", "c", "d", "e", "f", "g", "h"];

const puzzle = {
  boardEl: document.getElementById("board"),
  statusEl: document.getElementById("puzzle-status"),
  position: {},
  selected: null,
  step: 0, // 0 = waiting for Ra6, 1 = waiting for b7#, 2 = solved
  locked: false,
  statusKey: "puzzle_your_move",
  statusTone: "",
  timeouts: [],

  init() {
    // build 64 squares once
    for (let rank = 8; rank >= 1; rank--) {
      for (let f = 0; f < 8; f++) {
        const sq = FILES[f] + rank;
        const btn = document.createElement("button");
        btn.type = "button";
        btn.className = "square" + ((f + rank) % 2 === 1 ? " dark" : "");
        btn.dataset.square = sq;
        btn.addEventListener("click", () => this.onSquareClick(sq));
        this.boardEl.appendChild(btn);
      }
    }
    document.getElementById("puzzle-reset").addEventListener("click", () => this.reset());
    document.getElementById("puzzle-solve").addEventListener("click", () => this.playSolution());
    this.reset();
  },

  reset() {
    this.timeouts.forEach(clearTimeout);
    this.timeouts = [];
    this.position = { ...START_POSITION };
    this.selected = null;
    this.step = 0;
    this.locked = false;
    this.setStatus("puzzle_your_move", "");
    this.render();
  },

  later(fn, ms) {
    this.timeouts.push(setTimeout(fn, ms));
  },

  render(highlights = {}) {
    this.boardEl.querySelectorAll(".square").forEach((btn) => {
      const sq = btn.dataset.square;
      const piece = this.position[sq];
      btn.innerHTML = piece
        ? `<span class="${piece[0] === "w" ? "wpiece" : "bpiece"}">${PIECE_GLYPHS[piece]}</span>`
        : "";
      btn.classList.toggle("selected", this.selected === sq);
      btn.classList.toggle("last-move", Boolean(highlights.lastMove?.includes(sq)));
      btn.classList.toggle("mate", Boolean(highlights.mate?.includes(sq)));
    });
  },

  setStatus(key, tone) {
    this.statusKey = key;
    this.statusTone = tone;
    this.refreshStatus();
  },

  refreshStatus() {
    if (!this.statusEl) return;
    this.statusEl.textContent = copy[lang][this.statusKey] || "";
    this.statusEl.className = "puzzle-status" + (this.statusTone ? " " + this.statusTone : "");
  },

  applyMove(from, to, highlights) {
    this.position[to] = this.position[from];
    delete this.position[from];
    this.selected = null;
    this.render(highlights ?? { lastMove: [from, to] });
  },

  wrong() {
    this.selected = null;
    this.render();
    this.boardEl.classList.remove("shake");
    void this.boardEl.offsetWidth; // restart animation
    this.boardEl.classList.add("shake");
  },

  onSquareClick(sq) {
    if (this.locked || this.step >= 2) return;

    const piece = this.position[sq];

    if (this.selected === null) {
      if (piece && piece[0] === "w") {
        this.selected = sq;
        this.render();
      } else {
        this.setStatus("puzzle_pick_white", "bad");
      }
      return;
    }

    if (sq === this.selected) {
      this.selected = null;
      this.render();
      return;
    }

    if (piece && piece[0] === "w") {
      this.selected = sq;
      this.render();
      return;
    }

    const from = this.selected;

    if (this.step === 0) {
      if (from === "a1" && sq === "a6") {
        this.applyMove("a1", "a6");
        this.setStatus("puzzle_good", "ok");
        this.locked = true;
        this.later(() => {
          // Black takes the rook: bxa6 (the critical defence)
          this.applyMove("b7", "a6", { lastMove: ["b7", "a6"] });
          this.step = 1;
          this.locked = false;
        }, 700);
      } else if (from === "a1" && sq === "a7") {
        // Rxa7+?? Kxa7 — tempting check, but no mate
        this.setStatus("puzzle_wrong_check", "bad");
        this.wrong();
      } else {
        this.setStatus("puzzle_wrong", "bad");
        this.wrong();
      }
      return;
    }

    if (this.step === 1) {
      if (from === "b6" && sq === "b7") {
        this.applyMove("b6", "b7", { lastMove: ["b6", "b7"], mate: ["a8"] });
        this.step = 2;
        this.setStatus("puzzle_mate", "ok");
      } else {
        this.setStatus("puzzle_wrong", "bad");
        this.wrong();
      }
    }
  },

  playSolution() {
    this.reset();
    this.locked = true;
    this.later(() => this.applyMove("a1", "a6"), 300);
    this.later(() => this.applyMove("b7", "a6"), 1100);
    this.later(() => {
      this.applyMove("b6", "b7", { lastMove: ["b6", "b7"], mate: ["a8"] });
      this.step = 2;
      this.setStatus("puzzle_mate", "ok");
    }, 1900);
  },
};

